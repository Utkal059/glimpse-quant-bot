"""Generate the terminal's TypeScript contract from the Pydantic API models.

    python -m glimpse_quant_bot.server.typescript > frontend/src/lib/contract.ts

The JSON schema of every model in :mod:`glimpse_quant_bot.server.schemas` is
translated into ``readonly`` TypeScript interfaces. Unit-annotated fields
(``x-unit`` in the schema) become branded types from ``./units``, so a
``Millisats`` can never be passed where a ``PriceUnits`` quote is expected and
neither can be mixed with a bare ``number`` without an explicit conversion.

``tests/test_server.py`` regenerates the file and fails if the checked-in copy
drifts, which keeps the Python and TypeScript sides of the boundary identical.
"""

from __future__ import annotations

import json
import re
import sys
import typing
from collections.abc import Iterable, Mapping
from typing import Any, get_args, get_origin

from pydantic import BaseModel

from glimpse_quant_bot.server import schemas

UNIT_TYPES = {"millisats": "Millisats", "points": "PriceUnits", "probability": "Probability"}
PHRASES = ("ARM_PHRASE", "RELEASE_PHRASE", "LIVE_ORDER_PHRASE")
HEADER = """\
// AUTO-GENERATED by `python -m glimpse_quant_bot.server.typescript` from
// src/glimpse_quant_bot/server/schemas.py. Do not edit by hand: change the
// Pydantic models and regenerate (tests/test_server.py checks it is current).
//
// Units: *_millisats -> Millisats (integer), *_price / *_points -> PriceUnits
// (0-100 LS-LMSR quote scale), probabilities -> Probability (0-1).

import type { Millisats, PriceUnits, Probability } from "./units";
"""


def _models() -> list[type[BaseModel]]:
    """API models in source order (the bases themselves excluded)."""
    bases = (schemas.ApiModel, schemas.RequestModel)
    return [
        value
        for value in vars(schemas).values()
        if isinstance(value, type)
        and issubclass(value, bases)
        and value not in bases
        and value.__module__ == schemas.__name__
    ]


def _literal_aliases() -> dict[str, tuple[str, ...]]:
    aliases: dict[str, tuple[str, ...]] = {}
    for name, value in vars(schemas).items():
        if get_origin(value) is typing.Literal:
            aliases[name] = tuple(str(arg) for arg in get_args(value))
    return aliases


def _comment(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    cleaned = " ".join(text.replace("``", "`").split())
    return [f"{indent}/** {cleaned} */"]


class _Translator:
    def __init__(self) -> None:
        self.aliases = _literal_aliases()
        self._by_values = {frozenset(values): name for name, values in self.aliases.items()}
        self.enums: dict[str, tuple[str, ...]] = {}

    def type_of(self, schema: Mapping[str, Any]) -> str:
        if "$ref" in schema:
            return str(schema["$ref"]).rsplit("/", 1)[-1]
        if "anyOf" in schema:
            return " | ".join(dict.fromkeys(self.type_of(part) for part in schema["anyOf"]))
        if "const" in schema:
            return json.dumps(schema["const"])
        if "enum" in schema:
            values = tuple(str(v) for v in schema["enum"])
            alias = self._by_values.get(frozenset(values))
            return alias or " | ".join(json.dumps(v) for v in values)
        kind = schema.get("type")
        unit = schema.get("x-unit")
        if kind in ("integer", "number"):
            return UNIT_TYPES[str(unit)] if unit else "number"
        if kind == "string":
            return "string"
        if kind == "boolean":
            return "boolean"
        if kind == "null":
            return "null"
        if kind == "array":
            if "prefixItems" in schema:
                items = ", ".join(self.type_of(item) for item in schema["prefixItems"])
                return f"readonly [{items}]"
            inner = self.type_of(schema.get("items", {}))
            return f"readonly ({inner})[]" if " | " in inner else f"readonly {inner}[]"
        if kind == "object":
            extra = schema.get("additionalProperties")
            if isinstance(extra, Mapping):
                return f"Readonly<Record<string, {self.type_of(extra)}>>"
            return "Readonly<Record<string, unknown>>"
        return "unknown"

    def collect_enums(self, defs: Mapping[str, Any]) -> None:
        for name, schema in defs.items():
            if "enum" in schema and "properties" not in schema:
                self.enums[name] = tuple(str(v) for v in schema["enum"])

    def interface(self, model: type[BaseModel]) -> list[str]:
        response = issubclass(model, schemas.ApiModel)
        schema = model.model_json_schema(mode="serialization" if response else "validation")
        self.collect_enums(schema.get("$defs", {}))
        required = set(schema.get("required", ()))
        lines = _comment(model.__doc__, "")
        lines.append(f"export interface {model.__name__} {{")
        for field, prop in schema.get("properties", {}).items():
            lines.extend(_comment(prop.get("description"), "  "))
            # Responses always serialise every field; requests may omit defaults.
            optional = "" if response or field in required else "?"
            lines.append(f"  readonly {field}{optional}: {self.type_of(prop)};")
        lines.append("}")
        return lines


def _union(values: Iterable[str]) -> str:
    return " | ".join(json.dumps(value) for value in values)


def render() -> str:
    translator = _Translator()
    bodies = ["\n".join(translator.interface(model)) for model in _models()]
    out: list[str] = [HEADER]
    out.extend(
        f"export const {name} = {json.dumps(getattr(schemas, name))} as const;" for name in PHRASES
    )
    out.append("")
    for name, values in sorted(translator.enums.items()):
        out.append(f"export type {name} = {_union(values)};")
        constant = re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()
        listed = ", ".join(map(json.dumps, values))
        out.append(f"export const {constant}_VALUES = [{listed}] as const;")
    for name, values in translator.aliases.items():
        out.append(f"export type {name} = {_union(values)};")
    out.append("")
    out.append("\n\n".join(bodies))
    return "\n".join(out).rstrip() + "\n"


def main() -> None:
    sys.stdout.write(render())


if __name__ == "__main__":
    main()
